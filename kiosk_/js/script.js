/* ---------- cart ---------- */
function addItemToCart(targetCart, menu, quantity = 1) {
  const existing = targetCart.find((item) => item.id === menu.id);

  if (existing) {
    existing.quantity += quantity;
  } else {
    targetCart.push({
      id: menu.id,
      store_id: menu.store_id,
      store: menu.store,
      name: menu.name,
      price: menu.price,
      quantity
    });
  }
}

