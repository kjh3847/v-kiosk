function renderCart(cart, itemsElement, totalElement, countElement, type) {
  if (cart.length === 0) {
    itemsElement.innerHTML = `<p class="empty-cart">장바구니가 비어 있습니다.</p>`;
  } else {
    // 컴팩트 1줄 레이아웃: 이름 | − N + | 가격
    itemsElement.innerHTML = cart
      .map((item, index) => `
        <div class="cart-item" data-menu-id="${item.id}">
          <div class="cart-item-name">${item.name}</div>
          <div class="qty-wrap">
            <button class="qty-btn" onclick="changeQuantity('${type}', ${index}, -1)">−</button>
            <span class="qty-num">${item.quantity}</span>
            <button class="qty-btn plus" onclick="changeQuantity('${type}', ${index}, 1)">＋</button>
          </div>
          <div class="item-price">${formatPrice(item.price * item.quantity)}</div>
        </div>
      `)
      .join("");
  }

  const total = cart.reduce((sum, item) => sum + item.price * item.quantity, 0);
  const count = cart.reduce((sum, item) => sum + item.quantity, 0);

  totalElement.textContent = formatPrice(total);
  countElement.textContent = `${count}개`;
}

function changeQuantity(type, index, diff) {
  const targetCart = type === "touch" ? touchCart : voiceCart;
  if (!targetCart[index]) return;

  targetCart[index].quantity += diff;
  if (targetCart[index].quantity <= 0) targetCart.splice(index, 1);

  if (type === "touch") {
    renderTouchCart();
  } else {
    renderVoiceCart();
    updateVoiceSummary();
  }
}

function removeItem(type, index) {
  const targetCart = type === "touch" ? touchCart : voiceCart;
  targetCart.splice(index, 1);

  if (type === "touch") {
    renderTouchCart();
  } else {
    renderVoiceCart();
    updateVoiceSummary();
  }
}

