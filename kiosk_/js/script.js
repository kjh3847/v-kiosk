function handleVoiceInput(text) {
  const normalized = text.replace(/\s+/g, "");

  updateRecognitionStatus(`인식됨: ${text}`);

  if (normalized.includes("결제")) {
    openPaymentChoice("voice");
    return;
  }

  if (voiceStep === "category") {
    const categoryId = findVoiceCategoryBySpeech(normalized);
    if (!categoryId) {
      updateAiBubble("메뉴 이름을 말씀해주세요. 예: 김치찌개 주세요.", true, false);
      return;
    }

    selectVoiceCategory(categoryId);
    return;
  }

  if (voiceStep === "categoryMenu") {
    const menuList = getMenusByCategory(selectedVoiceCategoryId);
    const foundMenu = menuList.find((menu) => normalized.includes(menu.name.replace(/\s+/g, "")));

    if (!foundMenu) {
      updateAiBubble("메뉴를 다시 말씀하거나 버튼으로 선택해주세요.", true, false);
      return;
    }

    addVoiceMenu(foundMenu.id);
  }
}

