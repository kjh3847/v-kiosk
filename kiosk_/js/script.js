function resizeWaveCanvases() {
  if (!mainCanvas || !mainCtx || !miniCanvas || !miniCtx) return;
  mainCanvas.width = mainCanvas.offsetWidth * window.devicePixelRatio;
  mainCanvas.height = mainCanvas.offsetHeight * window.devicePixelRatio;
  mainCtx.setTransform(window.devicePixelRatio, 0, 0, window.devicePixelRatio, 0, 0);

  miniCanvas.width = miniCanvas.offsetWidth * window.devicePixelRatio;
  miniCanvas.height = miniCanvas.offsetHeight * window.devicePixelRatio;
  miniCtx.setTransform(window.devicePixelRatio, 0, 0, window.devicePixelRatio, 0, 0);

  initMainParticles();
  initMiniParticles();
}

function initMainParticles() {
  const count = 180;
  mainParticles = [];
  for (let i = 0; i < count; i++) {
    mainParticles.push({
      angle: (Math.PI * 2 * i) / count,
      speed: 0.002 + Math.random() * 0.004,
      noise: Math.random() * 100,
      pulse: Math.random() * Math.PI * 2
    });
  }
}

function initMiniParticles() {
  const count = 90;
  miniParticles = [];
  for (let i = 0; i < count; i++) {
    miniParticles.push({
      angle: (Math.PI * 2 * i) / count,
      speed: 0.003 + Math.random() * 0.003,
      noise: Math.random() * 100,
      pulse: Math.random() * Math.PI * 2
    });
  }
}

function drawMainWave() {
  if (!mainCtx || !mainCanvas) return;
  const width = mainCanvas.offsetWidth;
  const height = mainCanvas.offsetHeight;
  const cx = width / 2;
  const cy = height / 2;

  mainCtx.clearRect(0, 0, width, height);

  const baseRadius = Math.min(width, height) * 0.28;
  const amp = window.aiWaveSpeaking ? 28 : 12;
  const glow = window.aiWaveSpeaking ? 18 : 10;

  mainCtx.save();
  mainCtx.translate(cx, cy);

  for (let layer = 0; layer < 3; layer++) {
    mainCtx.beginPath();

    mainParticles.forEach((p, i) => {
      const wave =
        Math.sin(mainTime * (2.2 + layer * 0.35) + p.noise) * amp +
        Math.cos(mainTime * (1.4 + layer * 0.22) + p.pulse) * (amp * 0.35);

      const radius = baseRadius + wave + layer * 10;
      const x = Math.cos(p.angle + mainTime * p.speed * 16) * radius;
      const y = Math.sin(p.angle + mainTime * p.speed * 16) * radius;

      if (i === 0) {
        mainCtx.moveTo(x, y);
      } else {
        mainCtx.lineTo(x, y);
      }
    });

    mainCtx.closePath();

    const gradient = mainCtx.createLinearGradient(-baseRadius, 0, baseRadius, 0);
    gradient.addColorStop(0, "rgba(0,0,0,0.08)");
    gradient.addColorStop(0.35, "rgba(20,20,20,0.78)");
    gradient.addColorStop(0.7, "rgba(60,60,60,0.72)");
    gradient.addColorStop(1, "rgba(0,0,0,0.08)");

    mainCtx.strokeStyle = gradient;
    mainCtx.lineWidth = layer === 0 ? 2.4 : layer === 1 ? 1.8 : 1.4;
    mainCtx.shadowBlur = glow + layer * 6;
    mainCtx.shadowColor = layer === 0 ? "rgba(0,0,0,0.5)" : "rgba(80,80,80,0.35)";
    mainCtx.stroke();
  }

  mainParticles.forEach((p, i) => {
    if (i % 3 !== 0) return;

    const wave =
      Math.sin(mainTime * 2.1 + p.noise) * amp +
      Math.cos(mainTime * 1.5 + p.pulse) * (amp * 0.3);

    const radius = baseRadius + wave;
    const x = Math.cos(p.angle + mainTime * p.speed * 16) * radius;
    const y = Math.sin(p.angle + mainTime * p.speed * 16) * radius;

    const dotGradient = mainCtx.createRadialGradient(x, y, 0, x, y, 4);
    dotGradient.addColorStop(0, "rgba(255,255,255,0.95)");
    dotGradient.addColorStop(0.45, "rgba(50,50,50,0.82)");
    dotGradient.addColorStop(1, "rgba(0,0,0,0)");

    mainCtx.fillStyle = dotGradient;
    mainCtx.beginPath();
    mainCtx.arc(x, y, window.aiWaveSpeaking ? 2.8 : 2.1, 0, Math.PI * 2);
    mainCtx.fill();
  });

  mainCtx.restore();
  mainTime += 0.018;
  requestAnimationFrame(drawMainWave);
}

