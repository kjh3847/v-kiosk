function speakText(text) {
  if (!window.speechSynthesis) return;
  window.speechSynthesis.cancel();
  const utter = new SpeechSynthesisUtterance(text);
  utter.lang = "ko-KR";
  utter.rate = 1.0;
  utter.pitch = 1.0;
  utter.volume = 1.0;
  const voices = window.speechSynthesis.getVoices();
  const korVoice = voices.find(v => v.lang === "ko-KR");
  if (korVoice) utter.voice = korVoice;
  utter.onend = () => {
    if (pendingAutoListen) setTimeout(() => recordAndSendVoice(), 300);
    pendingAutoListen = false;
  };
  window.speechSynthesis.speak(utter);
}

function speakIfPossible(text, listenAfter = false) {
  pendingAutoListen = listenAfter;
  if (typeof speakText === "function") {
    speakText(text);
  } else if (listenAfter) {
   setTimeout(() => recordAndSendVoice(), 300);
  }
}

function updateAiBubble(text, speak = true, listenAfter = false) {
  aiBubbleText.textContent = text;
  if (speak) speakIfPossible(text, listenAfter);
}

